"""
Offline: builds bucket_data.py, the average equity of every postflop bucket.

    .venv/bin/python build_buckets.py [deals_per_street]

Not part of the submission (uses multiprocessing; the bot imports only the
generated bucket_data.py).

For each street, deals random hole cards, a random opponent hand and a
random runout, buckets our hand, and plays one showdown. One rollout per
deal is unbiased, so over millions of deals each bucket's mean is its
equity. Three columns, by the opponent's own bucket on the same board:

    any       a random hand
    cont      hands that keep playing: CONTINUE_MADE or better, or a draw in
              CONTINUE_DRAWS (what calls a bet)
    value     VALUE_MADE or better, or a draw in VALUE_DRAWS (what bets or
              raises for value)

Stats are kept at three levels, finest first, so the bot can fall back when
a fine bucket is rare: (street, made, draw, texture), (street, made, draw)
and (street, made).
"""

import random
import sys
from multiprocessing import Pool

from buckets import (
    CONTINUE_DRAWS, CONTINUE_MADE, DRAWS, MADE, TEXTURES, VALUE_DRAWS,
    VALUE_MADE, bucket,
)
from hand_eval import score

CHUNK = 50_000


def work(args):
    nb, deals, seed = args
    rng = random.Random(seed)
    stats = {}  # key -> [any_sum, any_n, cont_sum, cont_n, val_sum, val_n]
    street = nb - 3
    for _ in range(deals):
        c = rng.sample(range(52), 9)
        hero, opp, runout = c[0:2], c[2:4], c[4:9]
        board = runout[:nb]
        made, draw, tex = bucket(hero, board)
        omade, odraw, _ = bucket(opp, board)
        a = score(hero + runout)
        b = score(opp + runout)
        result = 1.0 if a > b else 0.5 if a == b else 0.0
        cont = omade <= CONTINUE_MADE or odraw in CONTINUE_DRAWS
        value = omade <= VALUE_MADE or odraw in VALUE_DRAWS
        for key in ((street, made, draw, tex), (street, made, draw, -1),
                    (street, made, -1, -1)):
            s = stats.get(key)
            if s is None:
                s = stats[key] = [0.0, 0, 0.0, 0, 0.0, 0]
            s[0] += result
            s[1] += 1
            if cont:
                s[2] += result
                s[3] += 1
            if value:
                s[4] += result
                s[5] += 1
    return stats


def main():
    per_street = int(sys.argv[1]) if len(sys.argv) > 1 else 3_000_000
    jobs = []
    for nb in (3, 4, 5):
        for k in range(per_street // CHUNK):
            jobs.append((nb, CHUNK, nb * 1_000_003 + k))
    print(f"{len(jobs)} jobs of {CHUNK} deals ({per_street} per street)")
    total = {}
    with Pool() as pool:
        for part in pool.imap_unordered(work, jobs):
            for key, s in part.items():
                t = total.get(key)
                if t is None:
                    total[key] = list(s)
                else:
                    for i in range(6):
                        t[i] += s[i]

    lines = [
        "# Generated by build_buckets.py: do not edit by hand.",
        f"# {per_street} random deals per street, one showdown each.",
        "",
        f"MADE = {MADE!r}",
        f"DRAWS = {DRAWS!r}",
        f"TEXTURES = {TEXTURES!r}",
        "",
        "# (street 0 flop / 1 turn / 2 river, made, draw, texture) -> (",
        "#   equity vs any hand, deals, vs continuing hands, deals,",
        "#   vs value hands, deals); equities per mille. draw / texture -1:",
        "#   all draws / textures (the fallback levels).",
        "BUCKET_STATS = {",
    ]
    for key in sorted(total):
        a, an, c, cn, v, vn = total[key]
        row = (
            round(1000 * a / an) if an else 500, an,
            round(1000 * c / cn) if cn else 500, cn,
            round(1000 * v / vn) if vn else 500, vn,
        )
        lines.append(f"    {key!r}: {row!r},")
    lines += ["}", ""]
    with open("bucket_data.py", "w") as f:
        f.write("\n".join(lines))
    print(f"wrote bucket_data.py: {len(total)} entries")


if __name__ == "__main__":
    main()
